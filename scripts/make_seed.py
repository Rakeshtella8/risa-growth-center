"""Build sql/03_seed.sql from Attendee_Dataset.xlsx.
Usage: python3 make_seed.py <Attendee_Dataset.xlsx> <out.sql>
Loads the 9 data sheets AS-IS (duplicates and non-external people included; the views clean them),
copies them to schema original (for reset), and seeds plan tables.
"""
import sys, pandas as pd, math, datetime as dt

SHEETS = {  # sheet -> (table, columns in table order, without row_id)
 'Event': ('event', ['event_name','history_start','history_end','event_starts_at','event_ends_at','timezone','currency','fictional']),
 'Targets': ('targets', ['effective_at','identified_external_people_goal','registration_goal','unique_external_visitors_goal','marketing_budget_inr','target_version']),
 'Campaigns': ('campaigns', ['campaign_id','campaign_name','channel','target_audience','objective','owner_id','owner_name','created_at','planned_start_at','planned_end_at']),
 'Daily Marketing': ('daily_marketing', ['activity_id','campaign_id','campaign_name','owner_id','owner_name','activity_date','impressions','clicks','reported_reach','landing_page_sessions','registration_starts','marketing_spend_inr','platform']),
 'People': ('people', ['person_id','person_name','person_type','first_seen_at','first_touch_source','first_campaign_id','first_campaign_name','owner_id','owner_name']),
 'Interest and Engagement': ('interactions', ['interaction_id','person_id','person_name','campaign_id','campaign_name','owner_id','owner_name','occurred_at','event_type','detail']),
 'Registrations': ('registrations', ['registration_id','person_id','person_name','campaign_id','campaign_name','owner_id','owner_name','registered_at']),
 'Registration History': ('registration_history', ['history_id','registration_id','person_id','person_name','campaign_id','campaign_name','owner_id','owner_name','effective_at','status']),
 'Check-ins': ('checkins', ['event_id','person_id','person_name','registration_id','campaign_id','campaign_name','owner_id','owner_name','occurred_at','result','verification','source']),
}

def lit(v):
    if v is None or (isinstance(v, float) and math.isnan(v)) or v is pd.NaT or (not isinstance(v,(str,bool)) and pd.isna(v)):
        return 'null'
    if isinstance(v, (bool,)) : return 'true' if v else 'false'
    if isinstance(v, (pd.Timestamp, dt.datetime)): return "'" + pd.Timestamp(v).strftime('%Y-%m-%d %H:%M:%S') + "'"
    if isinstance(v, (int,)) or (hasattr(v,'dtype') and 'int' in str(v.dtype)): return str(int(v))
    if isinstance(v, float): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def main(xlsx, out):
    x = pd.read_excel(xlsx, sheet_name=None)
    o = ['-- generated by scripts/make_seed.py; do not edit by hand', 'begin;']
    for sheet, (tab, cols) in SHEETS.items():
        d = x[sheet]
        o.append(f'truncate public.{tab}; truncate original.{tab};')
        rows = [ '(' + ','.join(lit(r[c]) for c in cols) + ')' for _, r in d.iterrows() ]
        for i in range(0, len(rows), 500):
            o.append(f"insert into public.{tab} ({','.join(cols)}) values\n" + ',\n'.join(rows[i:i+500]) + ';')
        o.append(f'insert into original.{tab} select * from public.{tab};')
    o.append("""
truncate plan_targets;
insert into plan_targets values
 ('2025_goal','2025 revised goal',3600,3200,2200,300000,'Targets sheet, revised plan 15 Mar 2025 [D]'),
 ('2026_base','2026 base plan',3677,3117,2670,300000,'Strategy model, base case [A]'),
 ('2026_stretch','2026 stretch plan',3896,3336,3205,300000,'Strategy model, stretch case [A]');
""")
    o.append('commit;')
    open(out, 'w').write('\n'.join(o) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
